// The host hands us the user's
// chosen app language verbatim, so an exact hit is the normal path; the base
// fallback only matters when a phone reports a regional tag such as "pt-BR".
const RTL_LANGS = new Set(["ar", "ckb", "fa", "he", "ur"]);

function normLocale(loc) {
  const raw = String(loc || "en");
  if (I18N[raw]) return raw;
  const lower = raw.toLowerCase();
  for (const k of Object.keys(I18N)) if (k.toLowerCase() === lower) return k;
  const base = lower.split(/[-_]/)[0];
  for (const k of Object.keys(I18N)) if (k.toLowerCase().split("-")[0] === base) return k;
  return "en";
}

// Direction is a property of the language, not of one hardcoded language. The
// previous form was `lang === "ar"`, which silently rendered Hebrew, Persian,
// Urdu and Sorani left-to-right once they existed.
function isRtl(lang) {
  return RTL_LANGS.has(normLocale(lang));
}
