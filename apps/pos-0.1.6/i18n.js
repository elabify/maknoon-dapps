// Normalize a host locale (e.g. "en-US", "zh-Hans-CN", "ar-AE") to one of our
// three string maps. We ship only Simplified Chinese, so any zh-* maps to it.
function normLocale(loc) {
  const l = String(loc || "en").toLowerCase();
  if (l.startsWith("ar")) return "ar";
  if (l.startsWith("zh")) return "zh-Hans";
  return "en";
}

// Look up a string in the active language, falling back to English then the raw
// key. `vars` interpolates {name} placeholders.
function t(key, vars) {
  const lang = window.__posLang || "en";
  const table = I18N[lang] || I18N.en;
  let s = (table[key] != null) ? table[key] : (I18N.en[key] != null ? I18N.en[key] : key);
  if (vars) for (const k in vars) s = s.split("{" + k + "}").join(String(vars[k]));
  return s;
}

// Fill every element tagged with a data-i18n* attribute. Called once at boot,
// after the language is resolved. Runtime-updated nodes (amount, equivalent,
// receive line, etc.) carry their data-i18n only for the pre-async initial state.
function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.setAttribute("placeholder", t(el.dataset.i18nPh)); });
}
